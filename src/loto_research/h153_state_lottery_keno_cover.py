def cover_ratio(k, payouts):
    denom = comb(N, k)
    return sum(
        prize * comb(DRAWN, hits) * comb(N - DRAWN, k - hits) / denom
        for hits, prize in payouts.items()
        if 0 <= hits <= k and 0 <= k - hits <= N - DRAWN
    )

