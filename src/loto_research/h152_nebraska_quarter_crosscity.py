def full_cover_ratio(k,pays):
    ways=comb(N,k)
    gross=0.0
    for j,p in pays.items():
        if j<=D and k-j<=N-D:
            gross += comb(D,j)*comb(N-D,k-j)*p
    cost=ways*COST
    return ways,cost,gross,gross/cost

